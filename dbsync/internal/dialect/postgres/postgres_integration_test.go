//go:build integration

package postgres

import (
	"context"
	"database/sql"
	"os"
	"testing"

	_ "github.com/jackc/pgx/v5/stdlib"

	"gitee.com/wangbenchi66/dbsync/internal/model"
)

func TestIntrospectPostgres(t *testing.T) {
	dsn := os.Getenv("DBSYNC_TEST_PG_DSN")
	if dsn == "" {
		dsn = "postgres://postgres:dbsync@127.0.0.1:55432/dbsync?sslmode=disable"
	}
	admin, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	ctx := context.Background()
	if _, err := admin.ExecContext(ctx, `DROP SCHEMA IF EXISTS dbsync_pg CASCADE; CREATE SCHEMA dbsync_pg`); err != nil {
		t.Fatal(err)
	}
	_, err = admin.ExecContext(ctx, `
CREATE TABLE dbsync_pg.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(100) COLLATE "C" NOT NULL,
  amount NUMERIC(10,2) NOT NULL DEFAULT 0,
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ,
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT ck_amount CHECK (amount >= 0)
);
CREATE TABLE dbsync_pg.child (
  id BIGINT PRIMARY KEY,
  uid BIGINT,
  CONSTRAINT fk_child_user FOREIGN KEY (uid) REFERENCES dbsync_pg.users(id)
);
CREATE INDEX idx_child_uid ON dbsync_pg.child(uid);
CREATE VIEW dbsync_pg.v_users AS SELECT id, email FROM dbsync_pg.users;
CREATE FUNCTION dbsync_pg.f_one() RETURNS integer LANGUAGE sql AS 'SELECT 1';
CREATE TRIGGER trg_users BEFORE INSERT ON dbsync_pg.users FOR EACH ROW EXECUTE FUNCTION suppress_redundant_updates_trigger();
`)
	if err != nil {
		t.Fatal(err)
	}
	db, err := Open(dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	s, err := Introspect(ctx, db, "dbsync_pg")
	if err != nil {
		t.Fatal(err)
	}
	if len(s.Tables) != 2 {
		t.Fatalf("表数=%d", len(s.Tables))
	}
	users := s.Table("users")
	if users == nil {
		t.Fatal("缺 users")
	}
	if c := users.Column("id"); c == nil || !c.Identity || c.Type.ID != model.TypeInt {
		t.Fatalf("id 不符: %+v", c)
	}
	if c := users.Column("email"); c == nil || c.Type.Collation != "C" {
		t.Fatalf("email collation 不符: %+v", c)
	}
	if c := users.Column("amount"); c == nil || c.Type.ID != model.TypeDecimal || c.Type.Precision != 10 || c.Type.Scale != 2 {
		t.Fatalf("amount 不符: %+v", c)
	}
	if c := users.Column("active"); c == nil || c.Type.ID != model.TypeBool {
		t.Fatalf("active 不符: %+v", c)
	}
	var hasFK, hasCheck bool
	for _, c := range s.Table("child").Constraints {
		if c.Kind == model.ConstraintFK && c.RefTable == "users" {
			hasFK = true
		}
	}
	for _, c := range users.Constraints {
		if c.Kind == model.ConstraintCheck && c.CheckExpr != "" {
			hasCheck = true
		}
	}
	if !hasFK || !hasCheck {
		t.Fatalf("约束缺失: fk=%v check=%v", hasFK, hasCheck)
	}
	if len(s.Views) != 1 || len(s.Routines) != 1 || len(s.Triggers) != 1 {
		t.Fatalf("对象不符: views=%d routines=%d triggers=%d", len(s.Views), len(s.Routines), len(s.Triggers))
	}
	if len(s.Views[0].Dependencies) != 1 || s.Views[0].Dependencies[0] != "users" {
		t.Fatalf("视图依赖不符: %+v", s.Views[0])
	}
}
